// Generates src/aliases.ts from the shared alias table (aliases.json at the repository root).
// Usage: node scripts/gen-aliases.mjs [path/to/aliases.json]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(process.argv[2] ?? resolve(here, "../../../aliases.json"));
const table = JSON.parse(readFileSync(source, "utf8")).aliases;

const entries = Object.keys(table)
  .sort()
  .map((k) => {
    if (typeof table[k] !== "string") throw new Error(`alias ${k} is not a string`);
    return `  ${JSON.stringify(k)}: ${JSON.stringify(table[k])},`;
  });

const header = [
  "// Generated by scripts/gen-aliases.mjs from aliases.json. Do not edit by hand.",
  `// Source: ${source.replace(/^.*\/tap\//, "tap/")}`,
  "",
  "/** Tool-name aliases from aliases.json. Keys are normalized names; values are canonical tool names. */",
  "export const BUILTIN_ALIASES: Readonly<Record<string, string>> = {",
  ...entries,
  "};",
  "",
];

const body = `
const SPACES = /^[\\t \\u00A0\\u1680\\u2000-\\u200A\\u202F\\u205F\\u3000]+|[\\t \\u00A0\\u1680\\u2000-\\u200A\\u202F\\u205F\\u3000]+$/g;

/**
 * Normalizes a tool name: lowercase, trim spaces, then "-" and " " become "_", then the alias table.
 * \`extraAliases\` (host-defined) is consulted first and may override the built-in table.
 */
export function normalizeToolName(name: string, extraAliases?: Readonly<Record<string, string>>): string {
  const n = name.toLowerCase().replace(SPACES, "").replace(/[- ]/g, "_");
  if (extraAliases && Object.hasOwn(extraAliases, n)) return extraAliases[n]!;
  return Object.hasOwn(BUILTIN_ALIASES, n) ? BUILTIN_ALIASES[n]! : n;
}
`;

writeFileSync(resolve(here, "../src/aliases.ts"), header.join("\n") + body);
console.log(`wrote src/aliases.ts with ${entries.length} aliases`);
