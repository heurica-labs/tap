#!/usr/bin/env python3
"""Generate src/heurica_tap/aliases.py from the shared aliases.json table.

Usage:
    python3 scripts/gen_aliases.py [path/to/aliases.json]

The default source is the aliases.json at the root of the tap repository,
two directories above this package. The generated module is committed.
"""

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
DEFAULT_SOURCE = os.path.normpath(os.path.join(PKG, "..", "..", "aliases.json"))
OUT = os.path.join(PKG, "src", "heurica_tap", "aliases.py")

TEMPLATE = '''"""Tool-name aliases and normalization (SPEC 6.4).

GENERATED by scripts/gen_aliases.py from aliases.json. Do not edit by hand;
regenerate instead. SOURCE_SHA256 identifies the table this file was built from.
"""

from typing import Dict, Optional

SOURCE_SHA256 = "%(sha)s"

# Non-normative table from aliases.json. Keys are already normalized.
ALIASES: Dict[str, str] = {
%(entries)s
}

_SPACES = " \\t\\u00a0\\u1680\\u2000\\u2001\\u2002\\u2003\\u2004\\u2005\\u2006\\u2007\\u2008\\u2009\\u200a\\u202f\\u205f\\u3000"


def _lookup_key(name: str) -> str:
    """Lowercase, trim whitespace, then turn '-' and ' ' into '_'."""
    return name.lower().strip(_SPACES).replace("-", "_").replace(" ", "_")


def normalize_tool_name(name: str, extra_aliases: Optional[Dict[str, str]] = None) -> str:
    """Return the canonical tool name for `name`.

    Names are lowercased, '-' and spaces become '_', then the alias table is
    applied. `extra_aliases` lets a host map its own names; it is consulted first.
    """
    key = _lookup_key(name)
    if extra_aliases:
        for alias, target in extra_aliases.items():
            if _lookup_key(alias) == key:
                return target
    return ALIASES.get(key, key)
'''


def main(argv):
    source = argv[1] if len(argv) > 1 else DEFAULT_SOURCE
    with open(source, "rb") as fh:
        raw = fh.read()
    data = json.loads(raw.decode("utf-8"))
    table = data["aliases"]
    for key, value in table.items():
        if key != key.lower() or "-" in key or " " in key:
            raise SystemExit("alias key must be normalized: %r" % key)
        if not isinstance(value, str) or not value:
            raise SystemExit("alias target must be a non-empty string: %r" % key)
    entries = "\n".join(
        "    %r: %r," % (key, table[key]) for key in sorted(table)
    )
    text = TEMPLATE % {"sha": hashlib.sha256(raw).hexdigest(), "entries": entries}
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d aliases) from %s" % (OUT, len(table), source))


if __name__ == "__main__":
    main(sys.argv)
